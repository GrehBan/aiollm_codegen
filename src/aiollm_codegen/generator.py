_NAME_LIMIT: Final = 60
_NAME_TAIL: Final = 48


def _model_name(value: str) -> str:
    """Keep contextual names readable and bounded for strict source limits."""
    name = ModelResolver().default_class_name_generator(value)
    if len(name) <= _NAME_LIMIT:
        return name
    suffix = hashlib.sha256(name.encode()).hexdigest()[:8]
    tail = name[-_NAME_TAIL:]
    return tail[0].upper() + tail[1:] + suffix


class _FieldMetadata(BaseModel):
    name: str
    alias: str
    original_name: str | None = None


class _ModelMetadata(BaseModel):
    class_name: str
    source_ref: str
    module: str = ""
    fields: list[_FieldMetadata] = []


class GenerationMetadata(BaseModel):
    """Backend schema identities and fields retained for package generation."""

    models: list[_ModelMetadata]


def _adapt(
    code: str, metadata: GenerationMetadata, *, request: bool, api: str | None
) -> str:
    """Attach upstream identities and split aliases without executing code."""
    tree = ast.parse(code)
    context = _documentation_context(tree, metadata, api)
    tree.body.insert(
        0, ast.Expr(ast.Constant("Provider models generated from OpenAPI."))
    )
    names: dict[str, str | tuple[()]] = {}
    models: list[str] = []
    for model in metadata.models:
        pointer = model.source_ref.split("#/components/schemas/", 1)[-1]
        names[model.class_name] = (
            unquote(pointer).replace("~1", "/").replace("~0", "~")
            if "/" not in pointer
            else ()
        )
    for node in ast.walk(tree):
        _adapt_aliases(node)
        if isinstance(node, ast.ClassDef):
            _adapt_class(node, names, context)
            if not request:
                _drop_inherited_extra(node)
            if not any(
                isinstance(base, ast.Name)
                and base.id in {"Enum", "IntEnum", "StrEnum"}
                for base in node.bases
            ):
                models.append(node.name)
        _validate_literal(node)
    show_null(tree)
    tree.body.extend(
        ast.Expr(
            ast.Call(
                func=ast.Attribute(
                    ast.Name(name, ast.Load()), "model_rebuild", ast.Load()
                ),
                args=[],
                keywords=[],
            )
        )
        for name in models
    )
    ast.fix_missing_locations(tree)
    if any(
        isinstance(node, ast.Name) and node.id == "_AiollmInputFile"
        for node in ast.walk(tree)
    ):
        tree.body.insert(
            2,
            ast.ImportFrom(
                module="aiollm.types.files",
                names=[ast.alias(name="InputFile", asname="_AiollmInputFile")],
                level=0,
            ),
        )
    return apply_builtin_formatter(
        "# Generated by aiollm-codegen. Do not edit.\n"
        + format_docstrings(ast.unparse(tree) + "\n"),
        line_length=79,
        string_normalization=True,
        python_version=PythonVersion.PY_313,
    )


def _adapt_aliases(node: ast.AST) -> None:
    """Separate constructor and wire aliases in generated Pydantic fields."""
    if not (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Name)
        and node.func.id == "Field"
    ):
        return
    for keyword in list(node.keywords):
        if keyword.arg == "alias":
            keyword.arg = "validation_alias"
            node.keywords.append(
                ast.keyword("serialization_alias", keyword.value)
            )


def _drop_inherited_extra(node: ast.ClassDef) -> None:
    """Remove ``extra="allow"`` that BaseAPITypeExtra already declares.

    Responses are generated with every model allowing extras, so a closed
    upstream schema does not reject provider additions; the declaration
    itself repeats the base class and is left out of the output.
    """
    for statement in list(node.body):
        if not (
            isinstance(statement, ast.Assign)
            and [ast.unparse(target) for target in statement.targets]
            == ["model_config"]
            and isinstance(config := statement.value, ast.Call)
            and ast.unparse(config.func) == "ConfigDict"
        ):
            continue
        config.keywords = [
            keyword
            for keyword in config.keywords
            if not (
                keyword.arg == "extra"
                and ast.unparse(keyword.value) == "'allow'"
            )
        ]
        if not config.keywords and not config.args:
            node.body.remove(statement)


def _documentation_context(
    tree: ast.Module, metadata: GenerationMetadata, api: str | None
) -> DocumentationContext:
    """Collect what class docstrings may say about each type's origin."""
    upstream: dict[str, str] = {}
    owners: dict[str, str] = {}
    for model in metadata.models:
        pointer = model.source_ref.split("#/components/schemas/", 1)[-1]
        root = unquote(pointer.partition("/")[0])
        root = root.replace("~1", "/").replace("~0", "~")
        owners[model.class_name] = root
        if "/" not in pointer:
            upstream[model.class_name] = root
    descriptions: dict[str, str] = {}
    for statement in tree.body:
        if isinstance(statement, ast.ClassDef):
            if text := ast.get_docstring(statement):
                descriptions[statement.name] = text
        elif isinstance(statement, ast.TypeAlias):
            text = next(
                (
                    keyword.value.value
                    for node in ast.walk(statement.value)
                    if isinstance(node, ast.Call)
                    for keyword in node.keywords
                    if keyword.arg == "description"
                    and isinstance(keyword.value, ast.Constant)
                    and isinstance(keyword.value.value, str)
                ),
                None,
            )
            if text:
                descriptions[statement.name.id] = text
    return DocumentationContext(api, upstream, owners, descriptions)


def _adapt_class(
    node: ast.ClassDef,
    names: dict[str, str | tuple[()]],
    context: DocumentationContext,
) -> None:
    """Attach upstream identities to models while preserving enum values."""
    description = class_documentation(node, context)
    if ast.get_docstring(node) is not None:
        node.body[0] = ast.Expr(ast.Constant(description))
    else:
        node.body.insert(0, ast.Expr(ast.Constant(description)))
    if node.name not in names or any(
        isinstance(base, ast.Name)
        and base.id in {"Enum", "IntEnum", "StrEnum"}
        for base in node.bases
    ):
        return
    assignment = ast.Assign(
        targets=[ast.Name("__upstream_schema__", ast.Store())],
        value=ast.parse(repr(names[node.name]), mode="eval").body,
    )
    node.body.insert(1, assignment)


def _validate_literal(node: ast.AST) -> None:
    """Reject type annotations and nonliteral JSON objects inside Literal."""
    if not (
        isinstance(node, ast.Subscript)
        and isinstance(node.value, ast.Name)
        and node.value.id == "Literal"
    ):
        return
    values = (
        node.slice.elts if isinstance(node.slice, ast.Tuple) else [node.slice]
    )
    for value in values:
        if isinstance(value, ast.Attribute):
            continue
        if isinstance(value, ast.UnaryOp) and isinstance(value.op, ast.USub):
            value = value.operand
        if not isinstance(value, ast.Constant) or type(value.value) not in (
            str,
            int,
            bool,
            type(None),
        ):
            raise ValueError(
                "Literal arguments must be real string, integer, "
                "boolean or null values: " + ast.unparse(node)
            )


def generate_models(
    source: Path,
    *,
    kind: Literal["request", "response"],
    schemas: Sequence[str] = (),
) -> str:
    """Generate one Python module from bundled OpenAPI component schemas.

    Requests use BaseAPIType and MISSING for omitted fields; responses use
    BaseAPITypeExtra and retain unknown fields. Generated modules require
    aiollm and Pydantic 2.14+. No input or generated code is executed.

    Args:
        source: Local OpenAPI JSON/YAML file.
        kind: The model profile to apply to all selected schemas.
        schemas: Optional component names; dependencies are included.

    Returns:
        Deterministic Python source, without writing the destination.

    Raises:
        ValueError: If the input or profile is unsupported.
        OSError: If input or temporary metadata cannot be read/written.
        datamodel_code_generator.Error: If backend generation fails.
    """
    if kind not in ("request", "response"):
        raise ValueError("kind must be 'request' or 'response'")
    request = kind == "request"
    document = load_schemas(source, request=request, schemas=schemas)
    result, _ = generate_document(document, kind=kind)
    return format_source(result)


def generate_document(
    document: dict[str, JsonValue],
    *,
    kind: Literal["request", "response"],
) -> tuple[str, GenerationMetadata]:
    """Generate one module and retain backend metadata for package layout.

    Raises:
        ValueError: If the profile is unsupported or nothing is generated.
        datamodel_code_generator.Error: If backend generation fails.
    """
    request = kind == "request"
    document = prepare_document(document, request=request)
    base = "BaseAPIType" if request else "BaseAPITypeExtra"
    with TemporaryDirectory(prefix="aiollm-codegen-") as directory:
        metadata_path = Path(directory) / "metadata.json"
        code = generate(
            document,
            input_file_type=InputFileType.OpenAPI,
            output_model_type=DataModelType.PydanticV2BaseModel,
            target_python_version=PythonVersion.PY_313,
            target_pydantic_version=TargetPydanticVersion.V2_14,
            base_class=f"aiollm.types.base.{base}",
            use_missing_sentinel=request,
            strict_nullable=True,
            snake_case_field=True,
            use_annotated=True,
            use_standard_collections=True,
            use_union_operator=True,
            use_type_alias=True,
            naming_strategy=NamingStrategy.FullPath,
            custom_class_name_generator=_model_name,
            enum_field_as_literal=LiteralType.All
            if request
            else LiteralType.One,
            use_schema_description=True,
            use_field_description=False,
            set_default_enum_member=True,
            use_enum_values_in_discriminator=True,
            read_const_beside_enum=True,
            extra_fields=None if request else "allow",
            use_one_literal_as_default=request,
            disable_timestamp=True,
            openapi_scopes=[OpenAPIScope.Schemas],
            formatters=[Formatter.BUILTIN],
            settings_path=Path(directory),
            allow_remote_refs=False,
            emit_model_metadata=metadata_path,
        )
        metadata = GenerationMetadata.model_validate_json(
            metadata_path.read_text("utf-8")
        )
    if not isinstance(code, str):
        raise ValueError("Expected a single generated module")
    info = document.get("info")
    title = info.get("title") if isinstance(info, dict) else None
    # Only a title that names an API reads well in "from the OpenAI API".
    api = title if isinstance(title, str) and title.endswith("API") else None
    adapted = _adapt(code, metadata, request=request, api=api)
    if not request:
        adapted = add_unknown_variants(adapted)
    return adapted, metadata
